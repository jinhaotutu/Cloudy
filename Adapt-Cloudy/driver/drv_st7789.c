    st7789_write_data(0x18);

    // LCM Control
    st7789_write_cmd(ST7789_LCMCTRL);
    st7789_write_data(0x2C);

    // VDV/VRH Enable
    st7789_write_cmd(ST7789_VDVVRHEN);
    st7789_write_data(0x01);

    // VRH Set
    st7789_write_cmd(ST7789_VRHS);
